package basic.c03_strings;

public class Strings {

    public static void main(String[] args) {

        // Cadenas de texto

        String name = "Brais";
        String surname = "Moure";


        // Operaciones Básicas
        // Concatenación
        System.out.println(name + " " + surname);

        // Longitud
        System.out.println(name.length());

        // Obtener caracter
        System.out.println(name.charAt(4));
    }
}
